export function projectThailandLatLng(lat: number, lng: number): { x: number; y: number } {
  const radLat = (lat * Math.PI) / 180;
  const rx = (lng * Math.PI) / 180;
  const ry = Math.log(Math.tan(Math.PI / 4 + radLat / 2));
  const x = THAILAND_MAP_VIEWBOX.offsetX + (rx - THAILAND_MAP_VIEWBOX.minRadX) * THAILAND_MAP_VIEWBOX.scaleRad;
  const y = THAILAND_MAP_VIEWBOX.offsetY + (THAILAND_MAP_VIEWBOX.maxMercY - ry) * THAILAND_MAP_VIEWBOX.scaleRad;
  return { x, y };
}


export function normalizeHospitalNameKey(name: string): string {
  return (name || '')
    .toLowerCase()
    .replace(/โรงพยาบาล|รพ\.?|รพ|hospital|ศูนย์การแพทย์|คณะแพทยศาสตร์/gi, '')
    .replace(/[()\[\].,\-\s]/g, '')
    .trim();
}

export function matchCatalogHospitalByName(rawName: string): ThailandHospitalEntry | undefined {
  const key = normalizeHospitalNameKey(rawName);
  if (!key || key.length < 2) return undefined;

  for (const item of THAILAND_HOSPITALS_CATALOG) {
    const mainKey = normalizeHospitalNameKey(item.name);
    if (mainKey === key || mainKey.includes(key) || key.includes(mainKey)) {
      return item;
    }
    if (item.aliases) {
      for (const alias of item.aliases) {
        const aliasKey = normalizeHospitalNameKey(alias);
        if (aliasKey && (aliasKey === key || aliasKey.includes(key) || key.includes(aliasKey))) {
          return item;
        }
      }
    }
  }
  return undefined;
}
